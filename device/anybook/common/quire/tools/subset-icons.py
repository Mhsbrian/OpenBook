"""Cuts Material Symbols Rounded (Apache-2.0) down to the icons the Quire note uses (docs/quire-design.md §4.6).

usage: subset-icons.py MaterialSymbolsRounded.ttf OUT_TTF OUT_KT

The variable font is 15 MB. The note needs about sixty icons at weight 400, grade 0, optical size 24, outlined and
filled, so the font is pinned at those axis values, keeps only the FILL axis, and keeps only the icons' Private Use
Area code points (no ligatures). OUT_KT is the Kotlin table of those code points (Icons.kt).
Needs fontTools (AOSP's external/fonttools works: FONTTOOLS=~/anybook/aosp/src/external/fonttools/Lib).
"""
import os
import sys

sys.path.insert(0, os.environ.get("FONTTOOLS", os.path.expanduser("~/anybook/aosp/src/external/fonttools/Lib")))
from fontTools import subset  # noqa: E402
from fontTools.ttLib import TTFont  # noqa: E402
from fontTools.varLib import instancer  # noqa: E402

# Every icon the note, the mirror and the agent picker draw. Kinds and Quire's own tools follow §4.6.
ICONS = """
add add_a_photo add_circle apps arrow_back arrow_downward arrow_drop_down arrow_forward arrow_upward cancel check
check_circle checklist chevron_right close cloud_off computer content_copy dark_mode delete drive_file_move edit
error event expand_less expand_more format_quote format_size help history hub image info key language lock mic
more_horiz more_vert open_in_browser open_in_full open_in_new open_in_new_down pause play_arrow psychology refresh
save search select_window settings shield stop_circle summarize terminal translate tune undo visibility warning
""".split()


def ligature_glyphs(font):
    """Maps each ligature's text (an icon name) to the glyph it produces."""
    cmap = font.getBestCmap()
    glyph_char = {g: chr(c) for c, g in cmap.items() if c < 0x80}
    out = {}
    for lookup in font["GSUB"].table.LookupList.Lookup:
        for sub in lookup.SubTable:
            if sub.LookupType == 7:  # extension
                sub = sub.ExtSubTable
            if getattr(sub, "LookupType", None) != 4:
                continue
            for first, ligs in sub.ligatures.items():
                for lig in ligs:
                    name = "".join(glyph_char.get(g, "?") for g in [first] + list(lig.Component))
                    out.setdefault(name, lig.LigGlyph)
    return out


def main():
    src, out_ttf, out_kt = sys.argv[1:4]
    font = TTFont(src)
    by_name = ligature_glyphs(font)
    pua = {}
    for cp, glyph in font.getBestCmap().items():
        if 0xE000 <= cp <= 0xF8FF or cp >= 0xF0000:
            pua.setdefault(glyph, cp)
    points = {}
    for name in ICONS:
        glyph = by_name.get(name)
        if glyph is None or glyph not in pua:
            sys.exit(f"subset-icons: no code point for {name!r}")
        points[name] = pua[glyph]
    # Subset first: the instancer is slow on 4000 glyphs, and fontTools 4.49 loses gvar entries if it runs first.
    opts = subset.Options()
    opts.layout_features = []
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=sorted(points.values()))
    sub.subset(font)
    axes = {a.axisTag for a in font["fvar"].axes}
    pinned = {k: v for k, v in {"wght": 400, "GRAD": 0, "opsz": 24}.items() if k in axes}
    font = instancer.instantiateVariableFont(font, pinned)
    font.save(out_ttf)
    with open(out_kt, "w") as f:
        f.write("// Copyright (C) 2026 The OpenBook Authors\n// SPDX-License-Identifier: Apache-2.0\n")
        f.write("// Generated by device/anybook/common/quire/tools/subset-icons.py. Do not edit.\n\n")
        f.write("package dev.openbook.quire.note\n\n")
        f.write("/** Material Symbols Rounded code points, in res/font/quire_symbols.ttf (Apache-2.0). */\n")
        f.write("object Icons {\n")
        for name in ICONS:
            const = name.upper()
            f.write(f"    const val {const} = \"\\u{points[name]:04X}\"\n")
        f.write("}\n")
    print(f"subset-icons: {len(points)} icons, {os.path.getsize(out_ttf)} bytes, axes kept: "
          f"{[a.axisTag for a in font['fvar'].axes] if 'fvar' in font else []}")


if __name__ == "__main__":
    main()
