#!/usr/bin/env python3
"""Generate the G14 module lists from kernel/devices/anybook/g14/modules.tsv, and check them against a dist.

usage: kernel-g14-modlists.py gen   [--tsv TSV] [--out DIR]
       kernel-g14-modlists.py check [--tsv TSV] [--out DIR] --dist DIST [--build BUILD.bazel]
                                    [--report FILE.md] [--json FILE]

  gen    writes DIR/ (default: the TSV's directory):
           vendor_boot.{bm,vm}.modules.list   first-stage set, for the Kleaf initramfs (comments allowed)
           vendor_boot.{bm,vm}.modules.load   first-stage load order (basenames, as on Googlebook)
           vendor_dlkm.modules.list           every AnyBook vendor module; both variants ship the same files
           vendor_dlkm.{bm,vm}.modules.load   second-stage load order
           modules.{bm,vm}.blocklist          "blocklist <name>.ko" lines, as Android's libmodprobe reads them
  check  regenerates into a temporary directory and fails if DIR differs, then checks the plan against DIST
         (a dist from scripts/kernel-build.sh: the .ko files and system_dlkm.modules.load):
           - each AnyBook vendor module (the module_outs list _ANYBOOK_AMD_MODULES in --build, default
             kernel/devices/anybook/BUILD.bazel) has exactly one row, and every row names a module in the dist
           - gki rows are GKI modules (system_dlkm.modules.load)
           - first stage is closed under dependencies: nothing there may need vendor_dlkm or system_dlkm,
             which are not mounted yet
           - every second-stage dependency is in first stage, earlier in the load order, or a GKI module
           - no loaded module depends on a blocklisted one
         Dependencies come from `modinfo -F depends` (kmod; the anybook-kernel image has it).

bm = bare metal (the GA403WR), vm = QEMU/Cuttlefish guests.
"""
import argparse
import csv
import filecmp
import json
import os
import re
import subprocess
import sys
import tempfile

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_TSV = os.path.join(R, "kernel/devices/anybook/g14/modules.tsv")
VARIANTS = ("bm", "vm")
COLUMN = {"bm": "bare_metal", "vm": "vm"}
HEADER = "# Generated by scripts/kernel-g14-modlists.py from modules.tsv ({}). Do not edit.\n"


def canon(name):
    return os.path.basename(name).removesuffix(".ko").replace("-", "_")


def read_tsv(path):
    with open(path) as f:
        lines = [l for l in f if not l.startswith("#")]
    rows = list(csv.DictReader(lines, delimiter="\t"))
    for r in rows:
        for v in VARIANTS:
            if r[COLUMN[v]] not in ("first_stage", "load", "block", "-"):
                sys.exit(f"{path}: {r['module']}: bad {COLUMN[v]} value {r[COLUMN[v]]!r}")
        if r["source"] not in ("anybook", "gki"):
            sys.exit(f"{path}: {r['module']}: bad source {r['source']!r}")
    return rows


def plan(rows, v):
    col = COLUMN[v]
    return {
        "first_stage": [r["module"] for r in rows if r[col] == "first_stage"],
        "load": [r["module"] for r in rows if r[col] == "load"],
        "block": [r["module"] for r in rows if r[col] == "block"],
    }


def write(path, lines, comment=None):
    with open(path, "w") as f:
        if comment:
            f.write(comment)
        f.writelines(l + "\n" for l in lines)


def gen(rows, out, tsv_name):
    os.makedirs(out, exist_ok=True)
    hdr = HEADER.format(tsv_name)
    for v in VARIANTS:
        p = plan(rows, v)
        # .list files feed Kleaf, which drops lines starting with '#'. .load and .blocklist files land on the
        # device as they are, so they carry no comments.
        write(f"{out}/vendor_boot.{v}.modules.list", p["first_stage"], hdr)
        write(f"{out}/vendor_boot.{v}.modules.load", p["first_stage"])
        write(f"{out}/vendor_dlkm.{v}.modules.load", p["load"])
        write(f"{out}/modules.{v}.blocklist", [f"blocklist {m}" for m in p["block"]])
    write(f"{out}/vendor_dlkm.modules.list", [r["module"] for r in rows if r["source"] == "anybook"], hdr)


def modinfo_depends(path):
    out = subprocess.run(["modinfo", "-F", "depends", path], capture_output=True, text=True, check=True).stdout
    return [d for d in out.strip().split(",") if d]


def vendor_modules(build):
    """Basenames of the .ko files in _ANYBOOK_AMD_MODULES, the vendor modules' module_outs."""
    text = open(build).read()
    block = re.search(r"^_ANYBOOK_AMD_MODULES = \[(.*?)^\]", text, re.S | re.M).group(1)
    return {os.path.basename(m) for m in re.findall(r'"([^"]+\.ko)"', block)}


def check(rows, dist, build):
    problems = []
    gki = {canon(l.strip()) for l in open(os.path.join(dist, "system_dlkm.modules.load")) if l.strip()}
    on_disk = {f for f in os.listdir(dist) if f.endswith(".ko")}
    vendor = vendor_modules(build)
    by_file = {}
    for r in rows:
        if r["module"] in by_file:
            problems.append(f"{r['module']}: listed twice")
        by_file[r["module"]] = r
        if r["module"] not in on_disk:
            problems.append(f"{r['module']}: not in the dist")
        elif r["source"] == "gki" and canon(r["module"]) not in gki:
            problems.append(f"{r['module']}: marked gki but not in system_dlkm.modules.load")
        elif r["source"] == "anybook" and canon(r["module"]) in gki:
            problems.append(f"{r['module']}: marked anybook but it is a GKI module")
    for f in sorted(vendor - set(by_file)):
        problems.append(f"{f}: vendor module with no row in modules.tsv")
    for r in rows:
        if r["source"] == "anybook" and r["module"] not in vendor:
            problems.append(f"{r['module']}: marked anybook but not in _ANYBOOK_AMD_MODULES")

    deps = {r["module"]: modinfo_depends(os.path.join(dist, r["module"])) for r in rows if r["module"] in on_disk}
    gki_needed = {}
    summary = {}
    for v in VARIANTS:
        p = plan(rows, v)
        fs = {canon(m) for m in p["first_stage"]}
        blocked = {canon(m) for m in p["block"]}
        seen = set(fs)
        for m in p["first_stage"]:
            for d in deps.get(m, []):
                if canon(d) not in fs:
                    problems.append(f"{v}: first-stage {m} needs {d}, which is not in first stage")
        for m in p["load"]:
            for d in deps.get(m, []):
                c = canon(d)
                if c in blocked:
                    problems.append(f"{v}: {m} needs blocklisted {d}")
                elif c in gki and c not in fs:
                    gki_needed.setdefault(c, set()).add(m)
                elif c not in seen:
                    problems.append(f"{v}: {m} needs {d}, which is not loaded before it")
            seen.add(canon(m))
        summary[v] = {k: len(p[k]) for k in p}
    return problems, summary, {k: sorted(s) for k, s in sorted(gki_needed.items())}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=("gen", "check"))
    ap.add_argument("--tsv", default=DEFAULT_TSV)
    ap.add_argument("--out")
    ap.add_argument("--dist")
    ap.add_argument("--build", default=os.path.join(R, "kernel/devices/anybook/BUILD.bazel"))
    ap.add_argument("--report")
    ap.add_argument("--json")
    a = ap.parse_args()
    out = a.out or os.path.dirname(os.path.abspath(a.tsv))
    rows = read_tsv(a.tsv)
    if a.cmd == "gen":
        gen(rows, out, os.path.basename(a.tsv))
        print(f"wrote lists for {len(rows)} modules to {out}")
        return
    if not a.dist:
        sys.exit("check needs --dist")
    with tempfile.TemporaryDirectory() as t:
        gen(rows, t, os.path.basename(a.tsv))
        stale = [f for f in sorted(os.listdir(t)) if not os.path.exists(os.path.join(out, f))
                 or not filecmp.cmp(os.path.join(t, f), os.path.join(out, f), shallow=False)]
    problems, summary, gki_needed = check(rows, a.dist, a.build)
    problems = [f"{f}: out of date, rerun `{os.path.basename(sys.argv[0])} gen`" for f in stale] + problems
    lines = ["# G14 module lists: check", "",
             f"- plan: `{os.path.relpath(a.tsv, R)}`, {len(rows)} rows",
             f"- dist: `{a.dist}`", ""]
    lines += ["| variant | first stage | vendor_dlkm load | blocklisted |", "|---|---|---|---|"]
    lines += [f"| {v} | {s['first_stage']} | {s['load']} | {s['block']} |" for v, s in summary.items()]
    lines += ["", "GKI modules (system_dlkm) that second-stage vendor modules link against:", ""]
    lines += [f"- `{g}`: {', '.join(m)}" for g, m in gki_needed.items()]
    lines += ["", f"**{len(problems)} problems**" + (":" if problems else ".")]
    lines += [f"- {p}" for p in problems]
    text = "\n".join(lines) + "\n"
    print(text, end="")
    if a.report:
        open(a.report, "w").write(text)
    if a.json:
        json.dump({"ok": not problems, "problems": problems, "summary": summary, "gki_needed": gki_needed},
                  open(a.json, "w"), indent=1)
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
