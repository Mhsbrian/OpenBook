#!/usr/bin/env bash
# Regenerate aosp/patches/frameworks/base/0001-OPENBOOK-fonts.xml-*.patch: AOSP's /system/etc/fonts.xml at our
# frameworks/base pin, rewritten by fonts-customization.py --legacy-fonts-xml so WebView and Chrome see the document
# fonts (ANAL-208, docs/googlebook-ui.md §2.1). Reads the pinned file with `git show` and builds the patch in a scratch
# repository, so the shared AOSP tree is not touched. Fixed author and date, so the patch only changes when the
# generator's output does. Run it after changing DOCS in fonts-customization.py.
#
# usage: fonts-legacy-patch.sh
# Env: AOSP_SRC (default ~/anybook/aosp/src)
set -euo pipefail
R=$(cd "$(dirname "$0")/../.." && pwd)
T=${AOSP_SRC:-${ANYBOOK_HOME:-$HOME/anybook}/aosp/src}
PIN=$(zcat "$R/evidence/2026-10-15-aosp/manifest-pinned.xml.gz" |
      sed -n 's/.* path="frameworks\/base" revision="\([0-9a-f]\{40\}\)".*/\1/p' | head -1)
W=$(mktemp -d); trap 'rm -rf "$W"' EXIT
ME=(env GIT_AUTHOR_NAME="AnyBook aosp-patches.sh" GIT_AUTHOR_EMAIL=noreply@anybook.invalid
    GIT_AUTHOR_DATE="2026-10-17T22:20:00-04:00" GIT_COMMITTER_NAME="AnyBook aosp-patches.sh"
    GIT_COMMITTER_EMAIL=noreply@anybook.invalid GIT_COMMITTER_DATE="2026-10-17T22:20:00-04:00")
git -C "$W" init -q; mkdir -p "$W/data/fonts"
git -C "$T/frameworks/base" show "$PIN:data/fonts/fonts.xml" > "$W/data/fonts/fonts.xml"
git -C "$W" add -A; "${ME[@]}" git -C "$W" commit -q -m "frameworks/base $PIN"
python3 -I "$R/scripts/ui/fonts-customization.py" --legacy-fonts-xml "$W/data/fonts/fonts.xml" > "$W/fonts.xml"
mv "$W/fonts.xml" "$W/data/fonts/fonts.xml"
git -C "$W" add -A
"${ME[@]}" git -C "$W" commit -q -F - <<'EOF'
OPENBOOK: fonts.xml: metric-compatible document fonts for WebView

WebView and Chrome render system fonts through Skia's SkFontMgr_Android,
which parses only /system/etc/fonts.xml, with font paths relative to
/system/fonts (Chromium 145 leaves the NDK font API, UseAndroidNDKFontAPI,
off). It never reads /product/etc/fonts_customization.xml, so the
document fonts OpenBook installs in /product/fonts reach the framework
but not web pages.

Declare them here too, as ../../product/fonts/<file>: Arimo, Tinos,
Cousine, Gelasio, Comic Relief, Archivo Black and Archivo Narrow. Point
arial, times new roman, courier new and georgia at them instead of
sans-serif, serif and serif-monospace, and add comic sans ms. Skia knows
a font only by the names this file gives it, so the families whose own
name has a space also get it (comic relief, archivo black, archivo
narrow). Skia keeps the first family a name maps to, so the old
aliases are removed rather than overridden. The framework itself reads
font_fallback.xml, not this file, so its fonts are unchanged; on a
product without the files Skia drops the empty families and these names
fall back to the default font.

Generated by OpenBook scripts/ui/fonts-customization.py --legacy-fonts-xml.
EOF
O=$R/aosp/patches/frameworks/base; mkdir -p "$O"; rm -f "$O"/0001-OPENBOOK-fonts.xml-*.patch
git -C "$W" format-patch -q --zero-commit --no-signature -N -1 -o "$O" HEAD
ls "$O"
