"""Stage the GSP firmware of NVIDIA's open kernel modules (ANAL-297) from NVIDIA's driver package, in Android's
/vendor/firmware layout, with the package's licence and a manifest. Python 3 standard library and the zstd tool.

usage: kernel-nvidia-open-firmware.py --pin TSV --run NVIDIA-Linux-x86_64-<version>.run --out DIR

  --pin  kernel/firmware/anybook-nvidia-open.tsv: the package's URL, sha256 and size, and each file to take from it
         with its install path, sha256 and size
  --run  the package, downloaded from the pinned URL (only its sha256 is trusted; nothing in it is executed: the
         makeself header's skip= line count is read, and the zstd tar after it is listed and read as data)
  --out  writes OUT/vendor/firmware/<install path>, OUT/firmware-nvidia-open.mk (PRODUCT_COPY_FILES, with
         $(ANYBOOK_G14_NVIDIA_FIRMWARE_DIR) set to OUT/vendor/firmware) and OUT/firmware-manifest-nvidia-open.{json,md}

Exit status 1 if the package or any file differs from the pin. The kernel loads the files from /vendor/firmware
(firmware_class.path), uncompressed: the GKI has FW_LOADER_COMPRESS off.
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import tarfile


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def payload_offset(run):
    """Byte offset of the makeself payload: the header's skip=N says it starts on line N."""
    with open(run, "rb") as f:
        head = f.read(1 << 20)
    m = re.search(rb"^skip=(\d+)$", head, re.M)
    if not m:
        raise SystemExit(f"{run}: no makeself skip= line in its header")
    lines = int(m.group(1)) - 1
    off = 0
    for _ in range(lines):
        off = head.index(b"\n", off) + 1
    return off


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--pin", required=True)
    ap.add_argument("--run", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    rows = [l.split("\t") for l in open(a.pin).read().splitlines() if l.strip() and not l.startswith("#")]
    pkg = next(r for r in rows if r[0] == "package")
    want = {r[1]: r for r in rows if r[0] in ("file", "licence")}
    problems = []
    got = sha256(a.run)
    if got != pkg[3] or os.path.getsize(a.run) != int(pkg[4]):
        raise SystemExit(f"{a.run}: sha256 {got}, {os.path.getsize(a.run)} bytes; the pin says {pkg[3]}, {pkg[4]}")

    if os.path.exists(a.out):
        shutil.rmtree(a.out)
    vf = os.path.join(a.out, "vendor/firmware")
    os.makedirs(vf)
    found = {}
    with open(a.run, "rb") as raw:
        raw.seek(payload_offset(a.run))
        z = subprocess.Popen(["zstd", "-dc"], stdin=raw, stdout=subprocess.PIPE)
        with tarfile.open(fileobj=z.stdout, mode="r|") as t:
            for m in t:
                if m.name not in want:
                    continue
                if not m.isreg():
                    problems.append(f"{m.name}: not a regular file in the package")
                    continue
                dst = os.path.join(vf, want[m.name][2])
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                with t.extractfile(m) as src, open(dst, "wb") as out:
                    shutil.copyfileobj(src, out)
                os.chmod(dst, 0o644)
                found[m.name] = dst
        z.stdout.close()
        if z.wait() != 0:
            problems.append("zstd failed on the package payload")

    manifest = []
    for name, r in want.items():
        if name not in found:
            problems.append(f"{name}: not in the package")
            continue
        h, size = sha256(found[name]), os.path.getsize(found[name])
        if h != r[3] or size != int(r[4]):
            problems.append(f"{name}: sha256 {h}, {size} bytes; the pin says {r[3]}, {r[4]}")
        manifest.append({"path": "vendor/firmware/" + r[2], "kind": r[0], "size": size, "sha256": h,
                         "source": f"{os.path.basename(pkg[1])}:{name}", "source_url": pkg[1]})

    with open(os.path.join(a.out, "firmware-nvidia-open.mk"), "w") as f:
        f.write("# Generated by scripts/kernel-nvidia-open-firmware.py (ANAL-297) from " + os.path.basename(pkg[1]) +
                ".\n# Set ANYBOOK_G14_NVIDIA_FIRMWARE_DIR to the staged vendor/firmware directory.\n"
                "PRODUCT_COPY_FILES += \\\n" +
                " \\\n".join(f"    $(ANYBOOK_G14_NVIDIA_FIRMWARE_DIR)/{m['path'].removeprefix('vendor/firmware/')}:"
                             f"$(TARGET_COPY_OUT_VENDOR)/firmware/{m['path'].removeprefix('vendor/firmware/')}"
                             for m in manifest) + "\n")
    fw = [m for m in manifest if m["kind"] == "file"]
    json.dump({"package": {"url": pkg[1], "sha256": pkg[3], "bytes": int(pkg[4])}, "files": manifest,
               "firmware_bytes": sum(m["size"] for m in fw), "problems": problems},
              open(os.path.join(a.out, "firmware-manifest-nvidia-open.json"), "w"), indent=1)
    md = ["# Firmware manifest: NVIDIA's open kernel modules on the G14 (ANAL-297)", "",
          f"- Package: `{os.path.basename(pkg[1])}`, sha256 `{pkg[3]}` ({pkg[1]})",
          f"- Firmware: {len(fw)} files, {sum(m['size'] for m in fw)} bytes, staged unmodified as `/vendor/firmware/...`",
          f"- Every file matches the pin: {'yes' if not problems else 'NO, see problems'}", "",
          "| Path | Bytes | sha256 | Source |", "|---|---|---|---|"]
    md += [f"| `{m['path']}` | {m['size']} | `{m['sha256']}` | {m['source']} |" for m in manifest]
    if problems:
        md += ["", "## Problems", ""] + [f"- {p}" for p in problems]
    open(os.path.join(a.out, "firmware-manifest-nvidia-open.md"), "w").write("\n".join(md) + "\n")
    print(f"staged {len(fw)} firmware files ({sum(m['size'] for m in fw)} bytes) and the licence in {vf}; "
          f"{len(problems)} problems")
    for p in problems:
        print("PROBLEM:", p)
    raise SystemExit(1 if problems else 0)


if __name__ == "__main__":
    main()
