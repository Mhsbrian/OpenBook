#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
# Stage OpenBook NVK, the NVIDIA driver for apps (ANAL-327, docs/nvk-openbook.md), into the AOSP tree for
# device/anybook/common/nvk/nvk.mk:
#   $AOSP/vendor/anybook/nvk/{Android.bp, lib64/..., licenses/, PROVENANCE.txt}
# The libraries are the nvk-rm-clean tree's build (scripts/mesa-android-build.sh -- nvk-rm-clean), local outputs that
# are never committed. Android.bp is generated: one cc_prebuilt_library_shared per library (the SDK variant an app
# embeds; no stripping, so the APK holds these exact bytes) and the package itself, OpenBookNvk: org.openbook.nvk in
# /vendor/app, with the libraries uncompressed in lib/x86_64 and ANGLE's own APK libraries (external/angle, with
# OpenBook's NVK patch) for OpenGL ES. The libraries' names in the package are the names Android's loaders ask for on
# the G14: vulkan.<ro.hardware.vulkan>.so (radv) and lib<API>_<ro.hardware.egl>.so (angle).
#
# Only the bytes listed in device/anybook/common/nvk/tested-bytes.txt are staged: the build that ANAL-326 tested.
# --untested stages other bytes, for a development image only (PROVENANCE.txt says so). The provenance gate
# (scripts/nvk-provenance-check.sh) runs first. Rerun after every rebuild. Runs on the host.
#   scripts/nvk-stage.sh [--untested]
set -euo pipefail
R=$(cd "$(dirname "$0")/.." && pwd); A=${ANYBOOK_HOME:-$HOME/anybook}
TREE=nvk-rm-clean; M=$A/mesa; SRC=$M/out/$TREE/vendor/lib64; D=${AOSP_SRC:-$A/aosp/src}/vendor/anybook/nvk
PIN=$R/device/anybook/common/nvk/tested-bytes.txt; MANIFEST=$R/device/anybook/common/nvk/AndroidManifest.xml
untested=; [ "${1:-}" = --untested ] && untested=1
"$R/scripts/nvk-provenance-check.sh" --quiet
[ -f "$SRC/hw/vulkan.nouveau.so" ] || { echo "no NVK build in $SRC (scripts/mesa-android-build.sh -- $TREE)" >&2; exit 1; }

# The manifest's build_time is the tested build's.
bt=$(sed -n 's/^# build_time: //p' "$PIN")
grep -q "android:value=\"$bt\"" "$MANIFEST" || { echo "AndroidManifest.xml's build_time is not $bt ($PIN)" >&2; exit 1; }

files=(); names=(); state=tested
while IFS=$'\t' read -r sha src name; do
  case $sha in '#'*|'') continue ;; esac
  [ -f "$SRC/$src" ] || { echo "missing $SRC/$src" >&2; exit 1; }
  have=$(sha256sum "$SRC/$src" | cut -d' ' -f1)
  if [ "$have" != "$sha" ]; then
    if [ -z "$untested" ]; then
      echo "$src is $have, not the tested $sha ($PIN). Rebuild from this commit, or --untested for a development image" >&2
      exit 1
    fi
    state=untested
  fi
  files+=("$src"); names+=("$name")
done < "$PIN"

rm -rf "$D"; mkdir -p "$D/lib64/hw" "$D/licenses"
for f in "${files[@]}"; do cp "$SRC/$f" "$D/lib64/$f"; done
# The manifest goes with the libraries: the staged directory is complete on its own, so a branch whose device tree
# has no device/anybook/common/nvk still builds in the shared AOSP tree (the module is then defined, not installed).
cp "$MANIFEST" "$D/AndroidManifest.xml"
# Licences: Mesa (MIT), the RM backend (MIT), libdrm (MIT), elfutils' libelf (LGPL-3.0-or-later; docs/mesa.md).
cp "$M/src/$TREE/docs/license.rst" "$D/licenses/mesa-license.rst"
cp "$R/mesa/nvk-rm-clean/backend/LICENSE" "$D/licenses/nvk-rm-backend-LICENSE"
sed -n '1,/^ \*\//p' "$M/src/$TREE/subprojects/libdrm-2.4.133/xf86drm.h" > "$D/licenses/libdrm-NOTICE"
cp "$M/src/deps/elfutils/COPYING-LGPLV3" "$D/licenses/elfutils-COPYING-LGPLV3"

mod(){ case $1 in vulkan.radv.so) echo openbook_nvk_vulkan ;; libnv_bionic_native.so) echo openbook_nvk_rm ;;
         libdrm.so) echo openbook_nvk_libdrm ;; libelf_mesa.so) echo openbook_nvk_libelf ;;
         *) echo "no module name for $1" >&2; exit 1 ;; esac; }
{
cat <<EOF
// Generated by scripts/nvk-stage.sh from $SRC ($state bytes). Do not edit; rerun the script.
// OpenBook NVK, the NVIDIA driver for apps: docs/nvk-openbook.md, device/anybook/common/nvk.

package {
    default_applicable_licenses: ["openbook_nvk_license"],
}

license {
    name: "openbook_nvk_license",
    visibility: [":__subpackages__"],
    license_kinds: [
        "SPDX-license-identifier-MIT",
        "SPDX-license-identifier-LGPL-3.0-or-later",
    ],
    license_text: [
        "licenses/mesa-license.rst",
        "licenses/nvk-rm-backend-LICENSE",
        "licenses/libdrm-NOTICE",
        "licenses/elfutils-COPYING-LGPLV3",
    ],
}
EOF
mods=()
for i in "${!files[@]}"; do
  m=$(mod "${names[$i]}"); mods+=("$m")
  cat <<EOF

// ${names[$i]} in the package: lib64/${files[$i]}, $(sha256sum "$D/lib64/${files[$i]}" | cut -c1-16)…
cc_prebuilt_library_shared {
    name: "$m",
    stem: "${names[$i]%.so}",
    sdk_version: "current",
    stl: "none",
    compile_multilib: "64",
    arch: { x86_64: { srcs: ["lib64/${files[$i]}"] } },
    strip: { none: true },
    check_elf_files: false,
    // Only inside the package: never installed on its own (its names clash with the system's libdrm, for one).
    installable: false,
    visibility: [":__subpackages__"],
}
EOF
done
cat <<EOF

// org.openbook.nvk: no code, the libraries uncompressed in lib/x86_64 (Android loads them from the APK). The build's
// default key signs it: it asks for no permission and runs no code of its own.
android_app {
    name: "OpenBookNvk",
    manifest: "AndroidManifest.xml",
    sdk_version: "current",
    vendor: true,
    compile_multilib: "64",
    use_embedded_native_libs: true,
    jni_libs: [
$(printf '        "%s",\n' "${mods[@]}" libEGL_angle libGLESv1_CM_angle libGLESv2_angle)
    ],
    aaptflags: [
        "--version-code",
        "3",
        "--version-name",
        "26.2.5-openbook.3",
    ],
    optimize: {
        enabled: false,
    },
}
EOF
} > "$D/Android.bp"

{ echo "staged: $(date -u +%FT%TZ) by scripts/nvk-stage.sh, OpenBook $(git -C "$R" rev-parse HEAD)$(git -C "$R" diff --quiet HEAD -- . || echo ' (uncommitted changes)')"
  echo "bytes: $state (device/anybook/common/nvk/tested-bytes.txt)"
  echo "from: $SRC"
  echo "mesa: $(git -C "$M/src/$TREE" rev-parse HEAD) ($(cat "$M/src/$TREE/VERSION"))"
  [ -f "$M/evidence/$TREE/versions.txt" ] && cat "$M/evidence/$TREE/versions.txt"
  echo; (cd "$D" && for i in "${!files[@]}"; do echo "$(sha256sum "lib64/${files[$i]}")  -> lib/x86_64/${names[$i]}"; done)
} > "$D/PROVENANCE.txt"
echo "staged OpenBook NVK ($state bytes) -> $D"
cat "$D/PROVENANCE.txt" | tail -n "${#files[@]}"
