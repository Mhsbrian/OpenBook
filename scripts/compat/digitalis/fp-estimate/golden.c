// Prints the probe's FRECPE/FRSQRTE golden table (scripts/compat/probe/jni/probe.cpp, group "regress") from the
// reference: run it with qemu-aarch64 (or on an Arm CPU). Scalar forms, FPCR 0 / FZ / DN, result and FPSR.
//   fp-estimate.sh golden > table
#include <stdint.h>
#include <stdio.h>

static const uint32_t kS[] = {0x3f800000, 0x40000000, 0x40400000, 0x3dcccccd, 0x3fc00000, 0x447a0000, 0x00800000,
                              0x00ffffff, 0x00400000, 0x00200000, 0x001fffff, 0x00000001, 0x7e800000, 0x7f000000,
                              0x7f7fffff, 0x00000000, 0x80000000, 0x7f800000, 0xff800000, 0x7fc12345, 0x7f812345,
                              0xbfc00000, 0xb8d1b717, 0x40800000, 0x41800000, 0x3e800000};
static const uint64_t kD[] = {0x3ff0000000000000, 0x4000000000000000, 0x4008000000000000, 0x3fb999999999999a,
                              0x0010000000000000, 0x0008000000000000, 0x0004000000000000, 0x0003ffffffffffff,
                              0x0000000000000001, 0x7fd0000000000000, 0x7fe0000000000000, 0x7fefffffffffffff,
                              0x0000000000000000, 0x8000000000000000, 0x7ff0000000000000, 0xfff0000000000000,
                              0x7ff8000000012345, 0x7ff0000000012345, 0xbff8000000000000, 0x4010000000000000};
static const uint64_t kFpcr[] = {0, 1u << 24, 1u << 25};

static void set_fpcr(uint64_t v) { __asm__ volatile("msr fpcr, %0" : : "r"(v)); }
static uint64_t fpsr(void) { uint64_t v; __asm__ volatile("mrs %0, fpsr" : "=r"(v)); return v; }
static void clear_fpsr(void) { __asm__ volatile("msr fpsr, xzr"); }

int main(void) {
  printf("// Generated by scripts/compat/digitalis/fp-estimate/golden.c under %s. {input, fpcr, frecpe, fpsr, frsqrte, fpsr}\n",
         "qemu-aarch64 -cpu max");
  printf("static const EstGolden32 kEstGolden32[] = {\n");
  for (unsigned c = 0; c < 3; c++)
    for (unsigned i = 0; i < sizeof kS / sizeof *kS; i++) {
      uint32_t r, q; uint64_t f1, f2;
      set_fpcr(kFpcr[c]);
      clear_fpsr(); __asm__ volatile("fmov s0, %w1\n frecpe s0, s0\n fmov %w0, s0" : "=r"(r) : "r"(kS[i]) : "v0"); f1 = fpsr();
      clear_fpsr(); __asm__ volatile("fmov s0, %w1\n frsqrte s0, s0\n fmov %w0, s0" : "=r"(q) : "r"(kS[i]) : "v0"); f2 = fpsr();
      set_fpcr(0);
      printf("    {0x%08x, 0x%llx, 0x%08x, 0x%llx, 0x%08x, 0x%llx},\n", kS[i], (unsigned long long)kFpcr[c], r,
             (unsigned long long)f1, q, (unsigned long long)f2);
    }
  printf("};\nstatic const EstGolden64 kEstGolden64[] = {\n");
  for (unsigned c = 0; c < 3; c++)
    for (unsigned i = 0; i < sizeof kD / sizeof *kD; i++) {
      uint64_t r, q, f1, f2;
      set_fpcr(kFpcr[c]);
      clear_fpsr(); __asm__ volatile("fmov d0, %1\n frecpe d0, d0\n fmov %0, d0" : "=r"(r) : "r"(kD[i]) : "v0"); f1 = fpsr();
      clear_fpsr(); __asm__ volatile("fmov d0, %1\n frsqrte d0, d0\n fmov %0, d0" : "=r"(q) : "r"(kD[i]) : "v0"); f2 = fpsr();
      set_fpcr(0);
      printf("    {0x%016llxull, 0x%llx, 0x%016llxull, 0x%llx, 0x%016llxull, 0x%llx},\n", (unsigned long long)kD[i],
             (unsigned long long)kFpcr[c], (unsigned long long)r, (unsigned long long)f1, (unsigned long long)q,
             (unsigned long long)f2);
    }
  printf("};\n");
  return 0;
}
