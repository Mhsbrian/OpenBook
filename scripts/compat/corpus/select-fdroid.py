#!/usr/bin/env python3
"""Pick the F-Droid part of the ARM-compat corpus (ANAL-180) from a local F-Droid index-v2.json.

For each curated package: the newest APK whose only native ABI is arm64-v8a, plus the x86_64-only APK
of the same release as a native control when F-Droid builds one. Writes fdroid.tsv (pinned sha256).
Usage: select-fdroid.py <index-v2.json> <out.tsv>
"""
import json
import sys

# package -> why it is in the corpus (what native technology it pushes through the bridge)
CURATED = [
    ("org.videolan.vlc", "C/C++ media stack (libvlc, FFmpeg), NEON decoders"),
    ("org.mozilla.fennec_fdroid", "Gecko browser: multi-process, SpiderMonkey JIT emits arm64 code"),
    ("org.koreader.launcher.fdroid", "LuaJIT (JIT emits arm64 code), MuPDF"),
    ("org.lichess.mobileV2", "Flutter (Dart AOT) plus Stockfish NEON engine"),
    ("org.localsend.localsend_app", "Flutter plus Rust (flutter_rust_bridge)"),
    ("org.godotengine.editor.v4", "Godot 4 editor, Vulkan/GLES3 renderer"),
    ("org.ogre.browser", "OGRE 3D engine sample browser, GLES3"),
    ("org.wesnoth.Wesnoth", "SDL2 C++ game"),
    ("net.osmand.plus", "C++ OpenGL map renderer"),
    ("net.gcompris.full", "Qt 6 / QML on GLES"),
    ("com.nesbox.tic", "SDL2 fantasy console with Lua/JS/Wren VMs"),
    ("io.github.divverent.aaaaxy", "Go plus Ebitengine (GLES)"),
    ("chat.simplex.app", "Haskell (GHC) runtime plus Kotlin Compose"),
    ("org.torproject.vpn", "Rust (Arti) plus VpnService"),
    ("io.element.android.x", "Rust Matrix SDK (UniFFI)"),
    ("org.tuxpaint", "SDL2 C drawing app"),
]
HEADER = ["package", "name", "role", "abi", "version_name", "version_code", "apk", "sha256", "size", "license", "source", "why"]


def main(index, out):
    d = json.load(open(index, encoding="utf-8"))
    rows = []
    for pkg, why in CURATED:
        p = d["packages"].get(pkg)
        if not p:
            print(f"missing from index: {pkg}", file=sys.stderr)
            continue
        vs = sorted(p["versions"].values(), key=lambda v: v["manifest"]["versionCode"], reverse=True)
        a64 = next((v for v in vs if v["manifest"].get("nativecode") == ["arm64-v8a"]), None)
        if not a64:
            print(f"no arm64-only APK: {pkg}", file=sys.stderr)
            continue
        vn = a64["manifest"].get("versionName", "")
        x64 = next((v for v in vs if v["manifest"].get("versionName") == vn and v["manifest"].get("nativecode") == ["x86_64"]), None)
        m = p["metadata"]
        name = (m.get("name") or {}).get("en-US") or pkg
        for v, role in ((a64, "arm64-only"), (x64, "x86_64-control")):
            if v:
                rows.append([pkg, name, role, v["manifest"]["nativecode"][0], vn, str(v["manifest"]["versionCode"]),
                             v["file"]["name"].lstrip("/"), v["file"]["sha256"], str(v["file"]["size"]),
                             m.get("license", ""), m.get("sourceCode", ""), why])
    with open(out, "w", encoding="utf-8") as f:
        f.write(f"# F-Droid corpus for scripts/compat/run-matrix.sh; generated by select-fdroid.py from index-v2.json "
                f"(repo timestamp {d['repo']['timestamp']}). APKs come from https://f-droid.org/repo/ and are sha256-pinned.\n")
        f.write("\t".join(HEADER) + "\n")
        for r in rows:
            f.write("\t".join(x.replace("\t", " ") for x in r) + "\n")
    print(f"{len(rows)} APKs -> {out}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
