#!/usr/bin/env python3
"""Write a repo local manifest that splits AOSP projects into source and binary (prebuilt) sets.

usage: aosp-local-manifest.py mirror|tree EXPANDED_MANIFEST OUT_XML

  mirror: remove the binary projects, so the full-history mirror holds only source projects.
  tree:   re-declare the binary projects with clone-depth="1" (shallow, no clone bundle). Source projects
          keep full history, borrowed from the mirror through `repo init --reference`.

Binary projects are prebuilt toolchains, SDKs and APKs: 643 of the 748 GB of history in the Android 17
manifest (googlesource clone.bundle sizes, 2026-10-15). Their history is of no use to us.
"""
import re
import sys
from xml.dom import minidom

BINARY = re.compile(r"(?i)prebuilt")
BINARY_EXTRA = {"platform/external/chromium-webview", "device/google/cuttlefish_vmm"}


def is_binary(name):
    return bool(BINARY.search(name)) or name in BINARY_EXTRA


def main():
    mode, src, out = sys.argv[1:4]
    if mode not in ("mirror", "tree"):
        sys.exit(__doc__)
    projects = [p for p in minidom.parse(src).getElementsByTagName("project") if is_binary(p.getAttribute("name"))]
    doc = minidom.Document()
    root = doc.appendChild(doc.createElement("manifest"))
    root.appendChild(doc.createComment(f" generated by AnyBook scripts/aosp-local-manifest.py {mode} "))
    for name in sorted({p.getAttribute("name") for p in projects}):
        root.appendChild(doc.createElement("remove-project")).setAttribute("name", name)
    if mode == "tree":
        for p in projects:
            p = p.cloneNode(True)
            p.setAttribute("clone-depth", "1")
            root.appendChild(doc.importNode(p, True))
    with open(out, "w") as f:
        doc.writexml(f, addindent="  ", newl="\n", encoding="UTF-8")
    print(f"{mode}: {len({p.getAttribute('name') for p in projects})} binary projects -> {out}")


if __name__ == "__main__":
    main()
