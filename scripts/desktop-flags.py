#!/usr/bin/env python3
"""Generate AnyBook's desktop aconfig value set: every flag the reference desktop image enables that our
build leaves disabled, limited to flags our AOSP tree declares.

usage: desktop-flags.py REF_AFLAGS OURS_AFLAGS AOSP_SRC OUTDIR [--release cp2a] [--extra pkg.flag ...]
  REF_AFLAGS / OURS_AFLAGS: `aflags list` output (scripts/desktop-capture.sh writes aflags.txt).
  OUTDIR: release dir, e.g. device/anybook/common/desktop/release. Writes aconfig/<release>/<package>/ with one
  <flag>_flag_values.textproto per flag (ENABLED, READ_ONLY as on the reference) and an Android.bp per
  package, replacing what was there. release_configs/ and the map are maintained by hand.
Only platform containers (system, system_ext, product, vendor) are taken; mainline-module flags follow the
module's own release and are only added with --extra.
"""
import argparse
import re
import shutil
import subprocess
from pathlib import Path

PLATFORM = {"system", "system_ext", "product", "vendor"}
DECL_DIRS = ["frameworks", "packages", "system", "build/make", "hardware/interfaces"]


def load(p):
    out = {}
    for line in Path(p).read_text(errors="replace").splitlines():
        t = line.split()
        if len(t) >= 3 and "." in t[0] and t[1] in ("enabled", "disabled"):
            out[t[0]] = (t[1], t[-1])
    return out


def declared(src, pkg, name):
    """True if some .aconfig file under src declares package `pkg` with flag `name`."""
    r = subprocess.run(["grep", "-rlE", "--include=*.aconfig", rf'^\s*name: "{name}"', *DECL_DIRS],
                       cwd=src, capture_output=True, text=True)
    for f in r.stdout.split():
        if re.search(rf'^package: "{re.escape(pkg)}"', (Path(src) / f).read_text(), re.M):
            return f
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("ref"); ap.add_argument("ours"); ap.add_argument("src"); ap.add_argument("out", type=Path)
    ap.add_argument("--release", default="cp2a")
    ap.add_argument("--extra", nargs="*", default=[])
    a = ap.parse_args()
    ref, ours = load(a.ref), load(a.ours)
    want = {}
    for f, (val, cont) in sorted(ref.items()):
        if val != "enabled" or ours.get(f, ("disabled",))[0] == "enabled":
            continue
        if cont not in PLATFORM and f not in a.extra:
            continue
        pkg, name = f.rsplit(".", 1)
        decl = declared(a.src, pkg, name)
        if decl:
            want.setdefault(pkg, []).append((name, decl))
        else:
            print(f"skip (not declared in this tree): {f}")
    base = a.out / "aconfig" / a.release
    for d in base.glob("*/"):
        shutil.rmtree(d)
    base.mkdir(parents=True, exist_ok=True)
    (base / "Android.bp").write_text(
        "// Generated by scripts/desktop-flags.py. Do not edit; rerun it.\n\n"
        f'aconfig_value_set {{\n    name: "aconfig_value_set-anybook_desktop-{a.release}",\n'
        '    srcs: [\n        "*/Android.bp",\n    ],\n}\n')
    n = 0
    for pkg, flags in sorted(want.items()):
        d = base / pkg
        d.mkdir()
        (d / "Android.bp").write_text(
            "// Generated by scripts/desktop-flags.py.\n\n"
            f'aconfig_values {{\n    name: "aconfig-values-anybook_desktop-{a.release}-{pkg}-all",\n'
            f'    package: "{pkg}",\n    srcs: [\n        "*_flag_values.textproto",\n    ],\n}}\n')
        for name, decl in flags:
            (d / f"{name}_flag_values.textproto").write_text(
                f'# Declared in {decl}\nflag_value {{\n  package: "{pkg}"\n  name: "{name}"\n'
                '  state: ENABLED\n  permission: READ_ONLY\n}\n')
            n += 1
    print(f"wrote {n} flags in {len(want)} packages to {base}")


if __name__ == "__main__":
    main()
