#!/usr/bin/env python3
"""Generate AnyBook's desktop aconfig value set (device/anybook/common/desktop/release).

Two sources write into the same value set:

diff mode (ANAL-169): every flag the reference desktop image enables that our build leaves disabled, limited to
flags our AOSP tree declares.
  desktop-flags.py REF_AFLAGS OURS_AFLAGS AOSP_SRC OUTDIR [--release cp2a] [--extra pkg.flag ...]
  REF_AFLAGS / OURS_AFLAGS: `aflags list` output (scripts/desktop-capture.sh writes aflags.txt).
  Only platform containers (system, system_ext, product, vendor) are taken; mainline-module flags follow the
  module's own release and are only added with --extra. Replaces the diff-mode files that were there.

list mode (ANAL-204): the flags named in a list file.
  desktop-flags.py --list LIST [--groups 1,2,...] AOSP_SRC OUTDIR [--release cp2a]
  LIST: one <package>.<flag> per line, or a TSV with a header whose first column is the flag. If the TSV has
  `decision` and `group` columns (device/anybook/common/desktop/release/googlebook-triage.tsv), only rows with
  decision `enable` are taken, and --groups limits them to those groups. Replaces the files an earlier run
  wrote from a list with the same file name and leaves everything else alone.

Both modes write ENABLED, READ_ONLY values, one <flag>_flag_values.textproto per flag in OUTDIR/aconfig/<release>/
<package>/ with an Android.bp per package; each file's first line records its source. A flag our tree doesn't
declare is skipped with a message. release_configs/ and the map are maintained by hand.
"""
import argparse
import re
import shutil
import subprocess
from pathlib import Path

PLATFORM = {"system", "system_ext", "product", "vendor"}
DECL_DIRS = ["frameworks", "packages", "system", "build/make", "hardware/interfaces"]
DIFF_MARK = "# Declared in "
LIST_MARK = "# From "


def load(p):
    out = {}
    for line in Path(p).read_text(errors="replace").splitlines():
        t = line.split()
        if len(t) >= 3 and "." in t[0] and t[1] in ("enabled", "disabled"):
            out[t[0]] = (t[1], t[-1])
    return out


def load_list(p, groups):
    lines = [l for l in Path(p).read_text().splitlines() if l.strip() and not l.startswith("#")]
    if not lines:
        return {}
    hdr = lines[0].split("\t")
    if hdr[0] != "flag":  # a plain list
        return {l.split()[0]: "" for l in lines}
    ix = {h: i for i, h in enumerate(hdr)}
    out = {}
    for l in lines[1:]:
        r = l.split("\t")
        if "decision" in ix and r[ix["decision"]] != "enable":
            continue
        g = r[ix["group"]] if "group" in ix else ""
        if groups and g not in groups:
            continue
        out[r[0]] = f"group {g}: {r[ix['reason']]}" if "reason" in ix else ""
    return out


def declarations(src):
    """{(package, flag): .aconfig file} for every flag declared under src's DECL_DIRS."""
    r = subprocess.run(["find", *DECL_DIRS, "-name", "*.aconfig", "-type", "f"], cwd=src, capture_output=True, text=True)
    out = {}
    for f in r.stdout.split():
        text = (Path(src) / f).read_text(errors="replace")
        m = re.search(r'^package: "([^"]+)"', text, re.M)
        if m:
            for name in re.findall(r'^\s*name: "([^"]+)"', text, re.M):
                out.setdefault((m.group(1), name), f)
    return out


def write_value(base, release, pkg, name, header):
    d = base / pkg
    if not (d / "Android.bp").exists():
        d.mkdir(parents=True, exist_ok=True)
        (d / "Android.bp").write_text(
            "// Generated by scripts/desktop-flags.py.\n\n"
            f'aconfig_values {{\n    name: "aconfig-values-anybook_desktop-{release}-{pkg}-all",\n'
            f'    package: "{pkg}",\n    srcs: [\n        "*_flag_values.textproto",\n    ],\n}}\n')
    (d / f"{name}_flag_values.textproto").write_text(
        f'{header}\nflag_value {{\n  package: "{pkg}"\n  name: "{name}"\n'
        '  state: ENABLED\n  permission: READ_ONLY\n}\n')


def remove_owned(base, owned):
    """Delete value files whose first line satisfies owned(line); then drop packages left without values."""
    for f in base.glob("*/*_flag_values.textproto"):
        if owned(f.read_text().split("\n", 1)[0]):
            f.unlink()
    for d in base.glob("*/"):
        if not any(d.glob("*_flag_values.textproto")):
            shutil.rmtree(d)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("args", nargs="+", help="REF OURS SRC OUT (diff mode) or SRC OUT (--list)")
    ap.add_argument("--release", default="cp2a")
    ap.add_argument("--extra", nargs="*", default=[])
    ap.add_argument("--list", type=Path)
    ap.add_argument("--groups", default="", help="comma-separated groups to take from --list (default: all)")
    a = ap.parse_args()
    if len(a.args) != (2 if a.list else 4):
        ap.error("diff mode takes REF OURS SRC OUT; --list takes SRC OUT")
    src, out = a.args[-2], Path(a.args[-1])
    base = out / "aconfig" / a.release
    base.mkdir(parents=True, exist_ok=True)
    want = {}  # full flag name -> header line
    if a.list:
        mark = f"{LIST_MARK}{a.list.name}"
        for f, why in load_list(a.list, set(filter(None, a.groups.split(",")))).items():
            want[f] = (mark + (f" {why}" if why else ""))
        remove_owned(base, lambda first: first == mark or first.startswith(mark + " "))
    else:
        ref, ours = load(a.args[0]), load(a.args[1])
        for f, (val, cont) in sorted(ref.items()):
            if val != "enabled" or ours.get(f, ("disabled",))[0] == "enabled":
                continue
            if cont not in PLATFORM and f not in a.extra:
                continue
            want[f] = None
        remove_owned(base, lambda first: first.startswith(DIFF_MARK))
    n, pkgs, decls = 0, set(), declarations(src)
    for f, header in sorted(want.items()):
        pkg, name = f.rsplit(".", 1)
        decl = decls.get((pkg, name))
        if not decl:
            print(f"skip (not declared in this tree): {f}")
            continue
        write_value(base, a.release, pkg, name, header or f"{DIFF_MARK}{decl}")
        n += 1
        pkgs.add(pkg)
    (base / "Android.bp").write_text(
        "// Generated by scripts/desktop-flags.py. Do not edit; rerun it.\n\n"
        f'aconfig_value_set {{\n    name: "aconfig_value_set-anybook_desktop-{a.release}",\n'
        '    srcs: [\n        "*/Android.bp",\n    ],\n}\n')
    total = len(list(base.glob("*/*_flag_values.textproto")))
    print(f"wrote {n} flags in {len(pkgs)} packages to {base}; the value set now holds {total}")


if __name__ == "__main__":
    main()
