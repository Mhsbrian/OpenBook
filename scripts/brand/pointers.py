# ------------------------------------------------------------------------------------------------- geometry
class Path:
    """Absolute commands: ('M', x, y), ('L', x, y), ('Q', cx, cy, x, y), ('C', c1x, c1y, c2x, c2y, x, y), ('Z',)."""

    def __init__(self, cmds=None):
        self.cmds = list(cmds or [])

    def __add__(self, other):
        return Path(self.cmds + other.cmds)

    def map(self, f):
        out = []
        for c in self.cmds:
            if c[0] == "Z":
                out.append(c)
                continue
            pts = [f(c[i], c[i + 1]) for i in range(1, len(c), 2)]
            out.append((c[0],) + tuple(v for p in pts for v in p))
        return Path(out)

    def rotate(self, deg, cx=12.0, cy=12.0):
        a = math.radians(deg)
        ca, sa = math.cos(a), math.sin(a)
        return self.map(lambda x, y: (cx + (x - cx) * ca - (y - cy) * sa, cy + (x - cx) * sa + (y - cy) * ca))

    def move(self, dx, dy):
        return self.map(lambda x, y: (x + dx, y + dy))

    def scale(self, s, cx=12.0, cy=12.0):
        return self.map(lambda x, y: (cx + (x - cx) * s, cy + (y - cy) * s))

    def d(self):
        def n(v):
            s = f"{v:.2f}".rstrip("0").rstrip(".")
            return "0" if s in ("-0", "") else s
        parts = []
        for c in self.cmds:
            parts.append(c[0] + ("" if c[0] == "Z" else " ".join(n(v) for v in c[1:])))
        return " ".join(parts)


def rpoly(points, radii):
    """A closed polygon with each corner rounded by a quadratic curve that starts radius dp along each edge."""
    if not isinstance(radii, (list, tuple)):
        radii = [radii] * len(points)
    n = len(points)
    cuts = []
    for i in range(n):
        p = points[i]
        a, b = points[i - 1], points[(i + 1) % n]
        r = radii[i]

        def toward(q, dist):
            dx, dy = q[0] - p[0], q[1] - p[1]
            ln = math.hypot(dx, dy)
            dist = min(dist, ln * 0.45)
            return (p[0] + dx / ln * dist, p[1] + dy / ln * dist)
        cuts.append((toward(a, r), p, toward(b, r)))
    cmds = [("M",) + cuts[0][2]]
    for i in range(1, n + 1):
        a, p, b = cuts[i % n]
        cmds.append(("L",) + a)
        cmds.append(("Q",) + p + b)
    cmds.append(("Z",))
    return Path(cmds)


def corner_tip(points, radii, i=0):
    """Where rounded corner i actually is: the midpoint of its curve (for hotspots)."""
    if not isinstance(radii, (list, tuple)):
        radii = [radii] * len(points)
    p, a, b = points[i], points[i - 1], points[(i + 1) % len(points)]

    def toward(q, dist):
        dx, dy = q[0] - p[0], q[1] - p[1]
        ln = math.hypot(dx, dy)
        dist = min(dist, ln * 0.45)
        return (p[0] + dx / ln * dist, p[1] + dy / ln * dist)
    ca, cb = toward(a, radii[i]), toward(b, radii[i])
    return (0.25 * ca[0] + 0.5 * p[0] + 0.25 * cb[0], 0.25 * ca[1] + 0.5 * p[1] + 0.25 * cb[1])


def subpaths(path):
    out, cur = [], []
    for c in path.cmds:
        if c[0] == "M" and cur:
            out.append(cur)
            cur = []
        cur.append(c)
    if cur:
        out.append(cur)
    return out


def area(sub):
    """Signed area of a subpath's control polygon; > 0 is clockwise on screen (y down)."""
    pts = [(c[-2], c[-1]) for c in sub if c[0] != "Z"]
    return 0.5 * sum(pts[i][0] * pts[(i + 1) % len(pts)][1] - pts[(i + 1) % len(pts)][0] * pts[i][1]
                     for i in range(len(pts)))


def reverse(sub):
    """The same closed subpath, traced the other way."""
    segs = []
    pos = sub[0][1:3]
    for c in sub[1:]:
        if c[0] == "Z":
            continue
        segs.append((pos, c))
        pos = c[-2:]
    out = [("M",) + tuple(pos)]
    for start, c in reversed(segs):
        if c[0] == "L":
            out.append(("L",) + tuple(start))
        elif c[0] == "Q":
            out.append(("Q", c[1], c[2]) + tuple(start))
        elif c[0] == "C":
            out.append(("C", c[3], c[4], c[1], c[2]) + tuple(start))
    out.append(("Z",))
    return out


def solid(path):
    """Every subpath clockwise, so overlapping shapes add up (union) under the non-zero fill rule."""
    return Path([c for sub in subpaths(path) for c in (sub if area(sub) > 0 else reverse(sub))])


def hole(path):
    """Every subpath anticlockwise: cut out of a solid() shape it overlaps."""
    return Path([c for sub in subpaths(path) for c in (sub if area(sub) < 0 else reverse(sub))])


def rrect(x, y, w, h, r):
    r = min(r, w / 2, h / 2)
    k = r * (1 - K)
    return Path([("M", x + r, y), ("L", x + w - r, y), ("C", x + w - k, y, x + w, y + k, x + w, y + r),
                 ("L", x + w, y + h - r), ("C", x + w, y + h - k, x + w - k, y + h, x + w - r, y + h),
                 ("L", x + r, y + h), ("C", x + k, y + h, x, y + h - k, x, y + h - r),
                 ("L", x, y + r), ("C", x, y + k, x + k, y, x + r, y), ("Z",)])


def circle(cx, cy, r):
    k = r * K
    return Path([("M", cx + r, cy), ("C", cx + r, cy + k, cx + k, cy + r, cx, cy + r),
                 ("C", cx - k, cy + r, cx - r, cy + k, cx - r, cy), ("C", cx - r, cy - k, cx - k, cy - r, cx, cy - r),
                 ("C", cx + k, cy - r, cx + r, cy - k, cx + r, cy), ("Z",)])


def bar(x0, y0, x1, y1, w):
    """A capsule from (x0, y0) to (x1, y1), w wide."""
    ang = math.degrees(math.atan2(y1 - y0, x1 - x0))
    ln = math.hypot(x1 - x0, y1 - y0)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    return rrect(cx - ln / 2 - w / 2, cy - w / 2, ln + w, w, w / 2).rotate(ang, cx, cy)


