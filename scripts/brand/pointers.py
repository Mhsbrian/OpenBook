def placed(name):
    """The icon, moved so that its own hotspot lands on AOSP's."""
    icon = ICONS[name]()
    hx, hy = icon["hotspot"]
    ax, ay = HOTSPOTS[name]
    dx, dy = ax - hx, ay - hy
    out = dict(icon)
    for k in ("shapes", "holes", "inner", "glyphs"):
        if out.get(k) is not None:
            out[k] = out[k].move(dx, dy)
    if "badge" in out:
        out["badge"] = (out["badge"][0].move(dx, dy), out["badge"][1])
    if "strokes" in out:
        out["strokes"] = [dict(st, stroke=st["stroke"].move(dx, dy)) for st in out["strokes"]]
    out["hotspot"] = (ax, ay)
    return out


def bounds(icon):
    """The drawn extent, outline included, from the path's points (control points too: a safe overestimate)."""
    xs, ys = [], []
    for c in icon["shapes"].cmds:
        if c[0] != "Z":
            xs += c[1::2]
            ys += c[2::2]
    return (min(xs) - OUTLINE, min(ys) - OUTLINE, max(xs) + OUTLINE, max(ys) + OUTLINE)


def layers(icon):
    """(kind, d, fill, stroke, width) in drawing order; fill/stroke are 'FILL', 'STROKE' or a #colour."""
    shapes = icon["shapes"] if "holes" in icon else solid(icon["shapes"])
    out = [("outline", shapes.d(), "STROKE", "STROKE", 2 * OUTLINE),
           ("body", shapes.d(), "FILL", None, 0)]
    if "holes" in icon:
        out.append(("glass", icon["holes"].d(), "STROKE", None, 0))
        out.append(("inner", solid(icon["inner"]).d(), "FILL", None, 0))
    if "badge" in icon:
        shape, color = icon["badge"]
        out.append(("badge", shape.d(), color, None, 0))
        if icon.get("glyphs") is not None:
            out.append(("glyph", solid(icon["glyphs"]).d(), WHITE, None, 0))
        for s in icon.get("strokes", []):
            out.append(("glyph-stroke", s["stroke"].d(), None, WHITE, s["width"]))
    return out


def vector_xml(icon):
    lines = [HEADER + '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             '    android:width="24dp"', '    android:height="24dp"', '    android:viewportWidth="24"',
             '    android:viewportHeight="24">']
    for kind, d, fill, stroke, width in layers(icon):
        attrs = [f'android:pathData="{d}"']
        if fill:
            attrs.append(f'android:fillColor="{FILL if fill == "FILL" else STROKE if fill == "STROKE" else fill}"')
        if stroke:
            attrs.append(f'android:strokeColor="{FILL if stroke == "FILL" else STROKE if stroke == "STROKE" else stroke}"')
            attrs += [f'android:strokeWidth="{width:g}"', 'android:strokeLineJoin="round"',
                      'android:strokeLineCap="round"']
        lines.append(f"    <!-- {kind} -->")
        lines.append("    <path\n        " + "\n        ".join(attrs) + " />")
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def svg(icon, fill="#000000", stroke="#FFFFFF", size=24, hotspot=False):
    def col(c):
        return {"FILL": fill, "STROKE": stroke}.get(c, c)
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 24 24">']
    for kind, d, f, s, w in layers(icon):
        if (f == "STROKE" or s == "STROKE") and stroke is None:
            continue
        a = f'd="{d}" fill="{col(f) if f else "none"}"'
        if s:
            a += f' stroke="{col(s)}" stroke-width="{w:g}" stroke-linejoin="round" stroke-linecap="round"'
        parts.append(f"<path {a}/>")
    if hotspot:
        hx, hy = icon["hotspot"]
        parts.append(f'<circle cx="{hx}" cy="{hy}" r="0.45" fill="#FF2D55"/>')
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.path.join(ASSETS, "pointer"))
    ap.add_argument("--check-aosp", metavar="AOSP_SRC", help="compare HOTSPOTS with this tree's icon files")
    a = ap.parse_args()
    if a.check_aosp:
        import re
        bad = 0
        for name, (hx, hy) in HOTSPOTS.items():
            f = os.path.join(a.check_aosp, "frameworks/base/core/res/res/drawable", f"pointer_{name}_vector_icon.xml")
            txt = open(f).read()
            got = tuple(float(re.search(rf'hotSpot{ax}="([\d.]+)dp"', txt).group(1)) for ax in "XY")
            if got != (hx, hy):
                print(f"{name}: AOSP {got}, pointers.py {(hx, hy)}")
                bad += 1
        print(f"hotspots: {len(HOTSPOTS) - bad}/{len(HOTSPOTS)} match")
        sys.exit(1 if bad else 0)
    dr = os.path.join(a.out, "drawable")
    pv = os.path.join(a.out, "preview")
    os.makedirs(dr, exist_ok=True)
    os.makedirs(pv, exist_ok=True)
    for name in ICONS:
        icon = placed(name)
        x0, y0, x1, y1 = bounds(icon)
        if x0 < -0.3 or y0 < -0.3 or x1 > 24.3 or y1 > 24.3:
            sys.exit(f"{name}: drawn outside the 24 dp box ({x0:.1f}, {y0:.1f}, {x1:.1f}, {y1:.1f})")
        with open(os.path.join(dr, f"pointer_{name}_vector.xml"), "w") as f:
            f.write(vector_xml(icon))
        with open(os.path.join(pv, f"{name}.svg"), "w") as f:
            f.write(svg(icon, hotspot=True))
    # aapt2 gives resource package "android" the framework's package ID 0x01, so the overlay's own resource IDs are
    # pinned to a type ID framework-res does not have (0x60): they can never be mistaken for a framework resource.
    with open(os.path.join(a.out, "stable-ids.txt"), "w") as f:
        for i, name in enumerate(ICONS):
            f.write(f"android:drawable/pointer_{name}_vector = 0x0160{i:04x}\n")
    print(f"{len(ICONS)} pointer icons in {dr}")


if __name__ == "__main__":
    main()
