def double_arrow(length=16.4, head=5.2, shaft=2.4, deg=0.0):
    """A double-headed arrow along x through (12, 12), rotated by deg."""
    h = length / 2
    hw = head / 2
    hl = head * 0.95
    s = shaft / 2
    pts = [(12 - h, 12), (12 - h + hl, 12 - hw), (12 - h + hl, 12 - s), (12 + h - hl, 12 - s), (12 + h - hl, 12 - hw),
           (12 + h, 12), (12 + h - hl, 12 + hw), (12 + h - hl, 12 + s), (12 - h + hl, 12 + s), (12 - h + hl, 12 + hw)]
    radii = [0.8, 0.7, 0.3, 0.3, 0.7, 0.8, 0.7, 0.3, 0.3, 0.7]
    return rpoly(pts, radii).rotate(deg)


